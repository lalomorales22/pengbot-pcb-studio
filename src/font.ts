/** Merged rectangles (mm) for a string. rot 0 = left→right, 90 = bottom→top. (x,y) = centre. px = pixel size mm. */
export function textRects(text: string, x: number, y: number, px: number, rot: 0 | 90 = 0): [number, number, number, number][] {
  const t = text.toUpperCase(), adv = 6, W = t.length * adv - 1, H = 7;
  const out: [number, number, number, number][] = [];
  [...t].forEach((ch, k) => {
    const g = FONT[ch] ?? FONT[' '];
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5;) {
        if (g[gy][gx] !== '1') { gx++; continue; }
        const s = gx; while (gx < 5 && g[gy][gx] === '1') gx++;
        // local coords: u along text, v up; origin = centre
        const u0 = k * adv + s - W / 2, u1 = k * adv + gx - W / 2, v1 = H / 2 - gy, v0 = v1 - 1;
        if (rot === 0) out.push([x + u0 * px, y + v0 * px, x + u1 * px, y + v1 * px]);
        else out.push([x - v1 * px, y + u0 * px, x - v0 * px, y + u1 * px]);
      }
    }
  });
  return out;
}
