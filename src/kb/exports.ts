export function kleJson(kb: Keyboard): string {
  const bx = keysBox(kb.keys), ks = [...kb.keys].sort((a, b) => b.y - a.y || a.x - b.x), rows: unknown[][] = [];
  let lastY = -1, curX = 0, row: unknown[] = [];
  for (const k of ks) {
    const y = (bx.y2 - k.y - U / 2) / U, x = (k.x - k.w * U / 2 - bx.x1) / U;
    if (Math.abs(y - lastY) > 0.25) { if (row.length) rows.push(row); row = []; const dy = lastY < 0 ? y : y - lastY - 1; curX = 0; lastY = y; if (Math.abs(dy) > 1e-3) row.push({ y: +dy.toFixed(3) }); }
    const o: Record<string, number> = {}; if (Math.abs(x - curX) > 1e-3) o.x = +(x - curX).toFixed(3); if (k.w !== 1) o.w = k.w;
    if (Object.keys(o).length) row.push(o); row.push(k.label ?? ''); curX = x + k.w;
  }
  if (row.length) rows.push(row);
  return JSON.stringify([{ name: kb.name, author: 'Penguin PCB Studio' }, ...rows], null, 0).replace(/\],\[/g, '],\n[') + '\n';
}

// ---------------- plate + case ----------------
interface Shape2D { poly: Pt[]; circles: [number, number, number][]; rects: Pt[][] }
function plateShapes(kb: Keyboard, b: KbBuild): Shape2D {
  const d = b.design, c = plateCut(kb.switch) / 2;
  const rects: Pt[][] = d.chips.filter(ch => ch.fp.startsWith('KEY_')).map(ch => [[-c, -c], [c, -c], [c, c], [-c, c]].map(([x, y]) => xf(x, y, ch.rot, ch.x, ch.y)));
  const u1 = d.chips.find(ch => ch.id === 'U1'); if (u1) { const [w, h] = proMicro.size, s = u1.rot % 180 ? [h, w] : [w, h]; rects.push([[u1.x - s[0] / 2 - 0.5, u1.y - s[1] / 2 - 0.5], [u1.x + s[0] / 2 + 0.5, u1.y - s[1] / 2 - 0.5], [u1.x + s[0] / 2 + 0.5, u1.y + s[1] / 2 + 0.5], [u1.x - s[0] / 2 - 0.5, u1.y + s[1] / 2 + 0.5]]); }
  const circles: [number, number, number][] = d.chips.filter(ch => ch.fp.startsWith('MH_')).map(ch => [ch.x, ch.y, ch.fp === 'MH_M2' ? 1.1 : 1.35]);
  if (kb.touchpad.on) { const ox = Math.min(...kb.outline.map(p => p[0])), oy = Math.min(...kb.outline.map(p => p[1])); circles.push([kb.touchpad.x - ox, kb.touchpad.y - oy, TOUCHPADS[kb.touchpad.kind].dia / 2 + 0.5]); }
  return { poly: d.outline!, circles, rects };
}
const fmt = (n: number) => +n.toFixed(3);
function svgDoc(W: number, H: number, body: string, title: string) {
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- ${title} — Penguin PCB Studio. Units: mm. Cut lines are 0.1 mm hairlines. -->\n<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(W + 10)}mm" height="${fmt(H + 10)}mm" viewBox="-5 -5 ${fmt(W + 10)} ${fmt(H + 10)}">\n<g fill="none" stroke="#000" stroke-width="0.1" transform="translate(0 ${fmt(H)}) scale(1 -1)">\n${body}</g>\n</svg>\n`;
}
const pathOf = (p: Pt[]) => `<path d="M${p.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join(' L')} Z"/>`;
export function plateSvg(kb: Keyboard, b: KbBuild) {
  const s = plateShapes(kb, b), d = b.design;
  return svgDoc(d.board.w, d.board.h, [pathOf(s.poly), ...s.rects.map(pathOf), ...s.circles.map(([x, y, r]) => `<circle cx="${fmt(x)}" cy="${fmt(y)}" r="${fmt(r)}"/>`)].join('\n') + '\n',
    `${kb.name} switch plate (${kb.switch === 'mx' ? 'MX 14.0 mm' : 'Choc 13.8 mm'} cutouts, 1.5 mm ${kb.switch === 'mx' ? 'steel/alu/FR4' : '1.2 mm'} plate; no stabilizer cutouts — use PCB-mount stabs)`);
}
export function plateDxf(kb: Keyboard, b: KbBuild) {
  const s = plateShapes(kb, b), L: string[] = ['0', 'SECTION', '2', 'HEADER', '9', '$INSUNITS', '70', '4', '0', 'ENDSEC', '0', 'SECTION', '2', 'ENTITIES'];
  const poly = (p: Pt[], layer: string) => { L.push('0', 'LWPOLYLINE', '8', layer, '90', String(p.length), '70', '1'); p.forEach(([x, y]) => L.push('10', fmt(x).toString(), '20', fmt(y).toString())); };
  poly(s.poly, 'OUTLINE'); s.rects.forEach(r => poly(r, 'CUTOUTS'));
  s.circles.forEach(([x, y, r]) => L.push('0', 'CIRCLE', '8', 'HOLES', '10', String(fmt(x)), '20', String(fmt(y)), '30', '0', '40', String(fmt(r))));
  L.push('0', 'ENDSEC', '0', 'EOF'); return L.join('\n') + '\n';
}
/** Simple tray case: PCB outline + 0.5 mm gap (inner wall) and a 3 mm wall (outer), mounting-hole bosses, USB opening marker. */
export function caseSvg(kb: Keyboard, b: KbBuild) {
  const d = b.design, raw = kb.outline.map(([x, y]) => [x - Math.min(...kb.outline.map(p => p[0])), y - Math.min(...kb.outline.map(p => p[1]))] as Pt);
  const inner = fillet(offset(raw, 0.5), kb.radius + 0.5), outer = fillet(offset(raw, 3.5), kb.radius + 3.5);
  const holes = d.chips.filter(ch => ch.fp.startsWith('MH_')).map(ch => `<circle cx="${fmt(ch.x)}" cy="${fmt(ch.y)}" r="2.5"/><circle cx="${fmt(ch.x)}" cy="${fmt(ch.y)}" r="${ch.fp === 'MH_M2' ? 0.8 : 1.05}"/>`);
  const u1 = d.chips.find(ch => ch.id === 'U1'); const usb = u1 ? (() => { const [x, y] = xf(0, 17, u1.rot, u1.x, u1.y); return `<rect x="${fmt(x - 6)}" y="${fmt(y - 4.5)}" width="12" height="9" stroke-dasharray="1 1"/>`; })() : '';
  return svgDoc(d.board.w + 7, d.board.h + 7, [pathOf(outer), pathOf(inner), ...holes, usb].join('\n') + '\n', `${kb.name} case outline (outer wall 3 mm, 0.5 mm PCB gap, M2/M2.5 bosses, dashed = USB-C opening)`).replace('viewBox="-5 -5', 'viewBox="-9 -9');
}
function offset(p: Pt[], dd: number): Pt[] {
  const ccw = polyArea(p) > 0, s = ccw ? 1 : -1, n = p.length;
  return p.map((q, i) => {
    const a = p[(i + n - 1) % n], b = p[(i + 1) % n];
    const n1 = nrm([(q[1] - a[1]) * s, -(q[0] - a[0]) * s]), n2 = nrm([(b[1] - q[1]) * s, -(b[0] - q[0]) * s]);
    const m = nrm([n1[0] + n2[0], n1[1] + n2[1]]), cos = m[0] * n1[0] + m[1] * n1[1], k = dd / Math.max(0.3, cos);
    return [q[0] + m[0] * k, q[1] + m[1] * k] as Pt;
  });
}
const nrm = (v: Pt): Pt => { const l = Math.hypot(v[0], v[1]) || 1; return [v[0] / l, v[1] / l]; };

/** Everything that is not a fab file: plate, case, firmware, KLE, design JSON. */
export function kitFiles(kb: Keyboard, b: KbBuild): Record<string, string> {
  const name = slug(kb.name);
  return {
    'plate/plate.svg': plateSvg(kb, b), 'plate/plate.dxf': plateDxf(kb, b), 'case/case-outline.svg': caseSvg(kb, b),
    'firmware/kmk/code.py': kmkCode(kb, b), ...prefix('firmware/', qmkFiles(kb, b)), ...prefix('firmware/', zmkFiles(kb, b)),
    'layout/kle.json': kleJson(kb), [`layout/${name}.penguin-kb.json`]: JSON.stringify(kb, null, 1),
    'README.txt': kitReadme(kb, b),
  };
}
const prefix = (p: string, o: Record<string, string>) => Object.fromEntries(Object.entries(o).map(([k, v]) => [p + k, v]));
function kitReadme(kb: Keyboard, b: KbBuild) {
  const m = b.matrix, tp = kb.touchpad.on ? TOUCHPADS[kb.touchpad.kind] : null;
  return `${kb.name} — cyberdeck keyboard kit (Penguin PCB Studio)
Board ${b.design.board.w.toFixed(1)} x ${b.design.board.h.toFixed(1)} mm, ${kb.keys.length} keys, ${kb.switch === 'mx' ? 'Cherry MX hotswap (Kailh CPG151101S11 sockets)' : 'Kailh Choc v1 hotswap (CPG135001S30 sockets)'}.
Controller: ${kb.controller === 'kb2040' ? 'Adafruit KB2040 (RP2040, USB-C) — KMK or QMK' : 'nice!nano v2 (nRF52840, BLE) — ZMK'} on a socketed Pro Micro footprint.
Matrix: ${m.rows} rows x ${m.cols} cols, COL2ROW, 1N4148W per key on the back.
Rows -> Pro Micro pins ${m.rowPins.join(', ')}; Cols -> ${m.colPins.join(', ')}.${Object.keys(m.special).length ? `\nSpecial: ${Object.entries(m.special).map(([k, v]) => `${k}=${v}`).join(', ')}` : ''}
${kb.i2c ? 'J1 QWIIC/I2C header to the cyberdeck host: GND, 3V3, SDA, SCL (Qwiic colour order).\n' : ''}${tp ? `J2 ${tp.name}: ${tp.pins.join(', ')}\n${tp.note}\n` : ''}
Files: plate/plate.svg + plate.dxf (laser-cut / 3D-print switch plate), case/case-outline.svg (tray case),
firmware/kmk/code.py (KB2040, CircuitPython), firmware/qmk/<kb>/ (keyboard.json, build with CONVERT_TO=kb2040),
firmware/zmk/ (nice!nano shield), layout/kle.json (re-open on keyboard-layout-editor.com).
`;
}

export async function kitZip(kb: Keyboard, b: KbBuild) { const z = new JSZip(); for (const [k, v] of Object.entries(kitFiles(kb, b))) z.file(k, v); return z; }
