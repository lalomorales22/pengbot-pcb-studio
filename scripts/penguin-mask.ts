// Regenerates src/laloPenguinMask.ts from public/samples/lalo-penguin.png (Lalo's hand-drawn penguin).
// Keeps only the dark ink lines (outline, eyes, pupils, belly line, feet) -> line-art mask, cropped to the penguin.
import { PNG } from 'pngjs';
import fs from 'node:fs';

const p = PNG.sync.read(fs.readFileSync('public/samples/lalo-penguin.png'));
const W = p.width, H = p.height;
const ink = (x: number, y: number) => { const i = (y * W + x) * 4; return 0.3 * p.data[i] + 0.59 * p.data[i + 1] + 0.11 * p.data[i + 2] < 90 && p.data[i + 3] > 127; };
let x0 = W, x1 = -1, y0 = H, y1 = -1;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (ink(x, y)) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
const w = x1 - x0 + 1, h = y1 - y0 + 1, rows: string[] = [];
for (let y = y0; y <= y1; y++) { let s = ''; for (let x = x0; x <= x1; x++) s += ink(x, y) ? '1' : '0'; rows.push(s.replace(/0+$/, '')); }
const src = `// AUTO-GENERATED by scripts/penguin-mask.ts from public/samples/lalo-penguin.png — do not edit.
// Lalo's penguin, dark ink lines only (1 = ink), cropped ${w}x${h} px. Row strings are right-trimmed.
export const LALO_PENGUIN = { width: ${w}, height: ${h}, rows: ${JSON.stringify(rows)} };
`;
fs.writeFileSync('src/laloPenguinMask.ts', src);
console.log(`lalo penguin mask ${w}x${h} -> src/laloPenguinMask.ts`);
